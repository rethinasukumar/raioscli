# raioscli/agents/executor.py

from raioscli.control.deploy import deploy_region
from raioscli.control.bootstrap import (
    bootstrap_controlplane,
    bootstrap_dataplane
)


class Executor:
    """
    Executes plans generated by Planner.
    """

    def execute(self, plan):
        for step in plan:

            print(f"[RAIOS] Executing: {step}")

            if step == "create_controlplane":
                bootstrap_controlplane()

            elif step == "create_dataplane":
                bootstrap_dataplane()

            elif step == "configure_controlplane":
                print("[RAIOS] Controlplane configured")

            elif step == "configure_dataplane":
                print("[RAIOS] Dataplane configured")

            elif step == "start_controlplane":
                print("[RAIOS] Controlplane started")

            elif step == "start_dataplane":
                print("[RAIOS] Dataplane started")

            elif step == "create_vm":
                deploy_region()

            elif step == "attach_disk":
                print("[RAIOS] Disk attached")

            elif step == "attach_seed_iso":
                print("[RAIOS] CloudInit ISO attached")

            elif step == "disable_secure_boot":
                print("[RAIOS] Secure Boot disabled")

            elif step == "set_boot_order":
                print("[RAIOS] Boot order configured")

            elif step == "start_vm":
                print("[RAIOS] VM started")

            else:
                raise ValueError(
                    f"Unknown execution step: {step}"
                )

